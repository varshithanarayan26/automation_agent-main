from datetime import datetime, UTC
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class AgentRequest(BaseModel):
    """Schema representing the user's natural language request to the autonomous agent."""

    request: str = Field(
        ...,
        description="The natural language request describing the document to generate (e.g., 'Draft a project plan for a new CRM migration').",
        min_length=5,
    )
    model_name: Optional[str] = Field(
        default=None,
        description="Optional specific LLM model identifier to use (e.g., 'gemini-1.5-flash'). Defaults to the system configured model.",
    )
    additional_context: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional key-value context to guide the planning/drafting process (e.g., target audience, company name, style preferences).",
    )


class Task(BaseModel):
    """Schema representing an individual execution step within the agent's plan (TODO list)."""

    id: str = Field(
        ...,
        description="Unique identifier for the task, typically sequential (e.g., 'task_01').",
    )
    title: str = Field(
        ...,
        description="A concise title describing the task.",
    )
    description: str = Field(
        ...,
        description="Detailed description of what this task must accomplish and its parameters.",
    )
    tool: str = Field(
        ...,
        description="The name of the tool to execute this task (e.g., 'web_search', 'draft_section', 'reflection_check').",
    )
    dependencies: List[str] = Field(
        default_factory=list,
        description="List of task IDs that must be successfully completed before this task can start execution.",
    )
    status: str = Field(
        default="pending",
        description="The current status of the task. Allowed values: 'pending', 'running', 'completed', 'failed'.",
    )
    result: Optional[str] = Field(
        default=None,
        description="The output data or markdown content generated by executing this task.",
    )
    error: Optional[str] = Field(
        default=None,
        description="The error traceback or explanation if the task execution failed.",
    )


class ExecutionPlan(BaseModel):
    """Schema representing the compiled execution plan (TODO list) containing all resolved tasks."""

    tasks: List[Task] = Field(
        ...,
        description="The ordered list of tasks required to fulfill the request.",
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="The UTC timestamp when this execution plan was generated.",
    )
    updated_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="The UTC timestamp when this execution plan was last updated.",
    )


class DocumentMetadata(BaseModel):
    """Schema representing the metadata of the compiled Microsoft Word (.docx) document."""

    title: str = Field(
        ...,
        description="The title of the generated document.",
    )
    doc_type: str = Field(
        ...,
        description="The type of structured business document (e.g., 'Product Specification', 'SOP', 'Business Proposal').",
    )
    file_name: str = Field(
        ...,
        description="The base name of the generated Word file (e.g., 'crm_migration_plan.docx').",
    )
    file_path: str = Field(
        ...,
        description="The local or relative storage path of the generated file.",
    )
    file_size_bytes: int = Field(
        ...,
        description="The size of the generated document file in bytes.",
    )
    word_count: int = Field(
        ...,
        description="The approximate word count of the generated document.",
    )
    section_count: int = Field(
        ...,
        description="The number of structural headings/sections added to the document.",
    )
    generated_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="The UTC timestamp when the document was successfully compiled.",
    )


class AgentResponse(BaseModel):
    """Schema representing the unified response returned by the API after agent execution completes."""

    request_id: str = Field(
        ...,
        description="A unique UUID identifying this specific agent execution run.",
    )
    request: str = Field(
        ...,
        description="The original user request that initiated the agent run.",
    )
    status: str = Field(
        ...,
        description="The terminal status of the execution: 'success', 'partial_success', or 'failed'.",
    )
    execution_plan: ExecutionPlan = Field(
        ...,
        description="The full list of tasks, execution logs, and outputs generated during the run.",
    )
    document_metadata: Optional[DocumentMetadata] = Field(
        default=None,
        description="The metadata of the generated Word document, if compilation succeeded.",
    )
    summary: str = Field(
        ...,
        description="A narrative executive summary highlighting what the agent researched, drafted, and compiled.",
    )
    reflection_notes: List[str] = Field(
        default_factory=list,
        description="Detailed logs from the Reflection/Self-Check phase, showing QA criteria tested and any corrective actions taken.",
    )
    error: Optional[str] = Field(
        default=None,
        description="Error details if the agent failed to execute the request.",
    )
