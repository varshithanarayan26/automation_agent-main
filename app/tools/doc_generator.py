import os
from datetime import datetime, UTC
from pathlib import Path
from typing import Any, Dict, List, Optional
from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor
from loguru import logger

from app.core.config import settings
from app.core.models import DocumentMetadata
from app.tools.base import tool_registry


class DocxBuilder:
    """Builder class to compile and style high-quality, professional MS Word documents (.docx)

    using a consistent typography and color design system.
    """

    def __init__(self, title: str, doc_type: str):
        """Initializes the document with styling presets."""
        self.title = title
        self.doc_type = doc_type
        self.doc = Document()

        # Design Colors (Navy Primary, Slate Secondary, Charcoal Body)
        self.COLOR_PRIMARY = RGBColor(10, 37, 64)  # #0A2540
        self.COLOR_SECONDARY = RGBColor(108, 117, 125)  # #6C757D
        self.COLOR_BODY = RGBColor(43, 43, 43)  # #2B2B2B

        # Apply Global Settings
        self._apply_page_setup()
        self._apply_global_styles()

    def _apply_page_setup(self) -> None:
        """Sets standard 1-inch margins on all sections."""
        for section in self.doc.sections:
            section.top_margin = Inches(1)
            section.bottom_margin = Inches(1)
            section.left_margin = Inches(1)
            section.right_margin = Inches(1)

    def _apply_global_styles(self) -> None:
        """Applies clean typography styles to the Normal font style."""
        style = self.doc.styles["Normal"]
        font = style.font
        font.name = "Calibri"
        font.size = Pt(11)
        font.color.rgb = self.COLOR_BODY

        # Add line spacing and space after paragraphs to Normal style
        p_format = style.paragraph_format
        p_format.line_spacing = 1.15
        p_format.space_after = Pt(6)

    def add_cover_page(self, subtitle: Optional[str] = None) -> None:
        """Generates a polished, minimal cover page with title, subtitle, and metadata."""
        # Top spacing
        for _ in range(3):
            self.doc.add_paragraph()

        # Add Document Type / Category
        p_type = self.doc.add_paragraph()
        run_type = p_type.add_run(self.doc_type.upper())
        run_type.bold = True
        run_type.font.size = Pt(10)
        run_type.font.color.rgb = self.COLOR_SECONDARY
        p_type.paragraph_format.space_after = Pt(2)

        # Add Main Title
        p_title = self.doc.add_paragraph()
        run_title = p_title.add_run(self.title)
        run_title.bold = True
        run_title.font.size = Pt(28)
        run_title.font.color.rgb = self.COLOR_PRIMARY
        p_title.paragraph_format.space_after = Pt(6)

        # Add Subtitle
        if subtitle:
            p_sub = self.doc.add_paragraph()
            run_sub = p_sub.add_run(subtitle)
            run_sub.font.size = Pt(14)
            run_sub.italic = True
            run_sub.font.color.rgb = self.COLOR_SECONDARY
            p_sub.paragraph_format.space_after = Pt(24)

        # Spacing before metadata block
        for _ in range(6):
            self.doc.add_paragraph()

        # Metadata Block
        p_meta = self.doc.add_paragraph()
        run_author = p_meta.add_run("PREPARED BY: Fluid AI Autonomous Agent\n")
        run_author.bold = True
        run_author.font.size = Pt(9.5)
        run_author.font.color.rgb = self.COLOR_SECONDARY

        run_date = p_meta.add_run(
            f"DATE: {datetime.now(UTC).strftime('%B %d, %Y')}\n"
        )
        run_date.bold = True
        run_date.font.size = Pt(9.5)
        run_date.font.color.rgb = self.COLOR_SECONDARY

        # Add page break
        self.doc.add_page_break()

    def add_header_footer(self) -> None:
        """Configures clean footers with timestamps and page numbers."""
        for section in self.doc.sections:
            # We want page numbers only, so enable header/footer linked defaults
            footer = section.footer
            p_foot = footer.paragraphs[0]
            p_foot.alignment = 2  # Right-aligned
            p_foot.text = ""  # Clear default

            # Add timestamp left, page number right
            run_time = p_foot.add_run(
                f"Generated by Fluid AI Agent | UTC: {datetime.now(UTC).strftime('%Y-%m-%d %H:%M')}      Page "
            )
            run_time.font.size = Pt(8.5)
            run_time.font.color.rgb = self.COLOR_SECONDARY

            # Insert simple page field XML code
            self._add_page_number_field(p_foot.add_run())

    def _add_page_number_field(self, run: Any) -> None:
        """Injects word-processor simple page numbering field code into the run XML."""
        fldChar1 = OxmlElement("w:fldChar")
        fldChar1.set(qn("w:fldCharType"), "begin")
        instrText = OxmlElement("w:instrText")
        instrText.set(qn("xml:space"), "preserve")
        instrText.text = "PAGE"
        fldChar2 = OxmlElement("w:fldChar")
        fldChar2.set(qn("w:fldCharType"), "separate")
        fldChar3 = OxmlElement("w:fldChar")
        fldChar3.set(qn("w:fldCharType"), "end")

        r = run._r
        r.append(fldChar1)
        r.append(instrText)
        r.append(fldChar2)
        r.append(fldChar3)

    def add_markdown_content(self, text: str) -> None:
        """Parses markdown-formatted text and adds it as styled Word elements.

        Supports Headings (#, ##, ###), lists, and paragraphs.
        """
        lines = text.split("\n")
        in_list = False

        for line in lines:
            stripped = line.strip()
            if not stripped:
                continue

            # Heading 1
            if stripped.startswith("# "):
                self.doc.add_heading(stripped[2:], level=1)
                in_list = False
            # Heading 2
            elif stripped.startswith("## "):
                self.doc.add_heading(stripped[3:], level=2)
                in_list = False
            # Heading 3
            elif stripped.startswith("### "):
                self.doc.add_heading(stripped[4:], level=3)
                in_list = False
            # Bullet Lists
            elif stripped.startswith("- ") or stripped.startswith("* "):
                self.doc.add_paragraph(stripped[2:], style="List Bullet")
                in_list = True
            # Standard Paragraphs
            else:
                p = self.doc.add_paragraph(stripped)
                in_list = False

    def add_styled_table(
        self, headers: List[str], rows: List[List[str]]
    ) -> None:
        """Generates a professional business grid table with colored headers."""
        table = self.doc.add_table(rows=1, cols=len(headers))
        table.style = "Table Grid"

        # Format Headers
        hdr_cells = table.rows[0].cells
        for col_idx, text in enumerate(headers):
            cell = hdr_cells[col_idx]
            cell.text = ""
            p = cell.paragraphs[0]
            run = p.add_run(text)
            run.bold = True
            run.font.color.rgb = RGBColor(255, 255, 255)
            run.font.size = Pt(10)

            # Apply Navy background shading to header cell
            tcPr = cell._tc.get_or_add_tcPr()
            shading = OxmlElement("w:shd")
            shading.set(qn("w:val"), "clear")
            shading.set(qn("w:color"), "auto")
            shading.set(qn("w:fill"), "0A2540")  # Navy Primary
            tcPr.append(shading)

        # Populate Rows
        for r_data in rows:
            row_cells = table.add_row().cells
            for col_idx, text in enumerate(r_data):
                row_cells[col_idx].text = text
                p = row_cells[col_idx].paragraphs[0]
                # Adjust cell margins and text spacing
                p.paragraph_format.line_spacing = 1.0
                p.paragraph_format.space_after = Pt(2)

        # Spacing after table
        self.doc.add_paragraph()

    def save(self, filename: str) -> Path:
        """Saves the document in the output directory, calculating file path.

        Args:
            filename: The target .docx filename.

        Returns:
            The absolute Path object where the file was saved.
        """
        # Extract base name and strip path traversal elements for security
        base_name = Path(filename).name
        if base_name.lower().endswith(".docx"):
            base_name = base_name[:-5]

        # Replace Windows-invalid filename characters (< > : " / \ | ? *) with underscores
        invalid_chars = ['<', '>', ':', '"', '/', '\\', '|', '?', '*']
        for c in invalid_chars:
            base_name = base_name.replace(c, "_")

        safe_name = f"{base_name}.docx"

        # Resolve path using app configuration settings singleton
        out_dir = settings.output_path
        file_path = out_dir / safe_name

        try:
            self.doc.save(str(file_path))
            # Verify file size > 0. If it failed or is 0 bytes, raise OSError
            if not file_path.exists() or file_path.stat().st_size == 0:
                if file_path.exists():
                    try:
                        file_path.unlink()
                    except Exception:
                        pass
                raise OSError("Generated file is 0 bytes or does not exist.")
            logger.info(f"Successfully compiled and saved document to: {file_path}")
            return file_path
        except (PermissionError, OSError) as e:
            logger.warning(
                f"File {file_path} is locked, inaccessible, or failed to write ({str(e)}). Generating a unique fallback filename."
            )
            # Cleanup any 0-byte file left from failed write
            if file_path.exists():
                try:
                    file_path.unlink()
                except Exception:
                    pass

            import uuid
            unique_name = f"{base_name}_{uuid.uuid4().hex[:8]}.docx"
            fallback_path = out_dir / unique_name
            try:
                self.doc.save(str(fallback_path))
                if not fallback_path.exists() or fallback_path.stat().st_size == 0:
                    if fallback_path.exists():
                        try:
                            fallback_path.unlink()
                        except Exception:
                            pass
                    raise OSError("Fallback generated file is 0 bytes or does not exist.")
                logger.info(f"Saved document to unique fallback path: {fallback_path}")
                return fallback_path
            except Exception as inner_e:
                # Cleanup fallback if left 0 bytes
                if fallback_path.exists():
                    try:
                        fallback_path.unlink()
                    except Exception:
                        pass
                logger.error(f"Failed to save document to fallback path: {inner_e}")
                raise inner_e


# Define helper to compute approximate word counts
def count_words(text: str) -> int:
    return len(text.split())


# Automatically register the document compiler with the Tool Registry
@tool_registry.register("compile_document")
def compile_document_tool(
    task_title: str, task_description: str, dependency_context: Dict[str, Any]
) -> str:
    """A tool wrapper that extracts drafts from dependencies and compiles the final styled DOCX.

    Args:
        task_title: Name of the task.
        task_description: Directions on what to compile.
        dependency_context: Context payload mapping task IDs to drafted text output.

    Returns:
        JSON string representation of the generated DocumentMetadata.
    """
    logger.info("Tool 'compile_document' invoked.")

    # 1. Resolve document titles and headers from dependencies or description
    doc_title = "Strategic Business Report"
    doc_type = "Business Report"

    # Attempt to extract document details from task description
    if "title:" in task_description.lower():
        try:
            parts = task_description.split("\n")
            for p in parts:
                if p.lower().startswith("title:"):
                    doc_title = p.split(":", 1)[1].strip()
                elif p.lower().startswith("type:"):
                    doc_type = p.split(":", 1)[1].strip()
        except Exception:
            pass

    # 2. Instantiate styled DocxBuilder
    builder = DocxBuilder(title=doc_title, doc_type=doc_type)
    builder.add_cover_page(subtitle="Autonomous Agent Compiled Intelligence")

    # 3. Aggregate section drafts chronologically in dependency order
    compiled_text_accumulator = []
    word_count = 0
    section_count = 0

    # Sort dependencies by ID (e.g. task_01, task_02) to ensure chronological order
    sorted_task_ids = sorted(dependency_context.keys())

    for task_id in sorted_task_ids:
        content = dependency_context[task_id]
        if not content:
            continue

        # Skip search result output to prevent polluting draft
        if "### Research Results" in content or "Research Results for query" in content:
            logger.debug(f"Skipping search task {task_id} during document draft compile.")
            continue

        logger.info(f"Adding drafted sections from {task_id} to document structure.")
        builder.add_markdown_content(content)
        compiled_text_accumulator.append(content)
        word_count += count_words(content)

        # Count headings (# or ##) in markdown content
        headings = [
            line
            for line in content.split("\n")
            if line.strip().startswith("# ")
            or line.strip().startswith("## ")
            or line.strip().startswith("### ")
        ]
        section_count += len(headings) if headings else 1

    # Add Footers
    builder.add_header_footer()

    # Create safe filename based on document title
    file_name = doc_title.lower().replace(" ", "_").replace("/", "_") + ".docx"

    # 4. Save file to Disk
    try:
        saved_path = builder.save(file_name)
        file_name = saved_path.name  # Use actual sanitized filename
        file_size = saved_path.stat().st_size
    except Exception as e:
        logger.error(f"Failed to write file to disk: {e}")
        # Safe fallback in current working dir
        # Ensure the fallback name is sanitized
        invalid_chars = ['<', '>', ':', '"', '/', '\\', '|', '?', '*']
        base_name = file_name[:-5] if file_name.lower().endswith(".docx") else file_name
        for c in invalid_chars:
            base_name = base_name.replace(c, "_")
        fallback_name = f"{base_name}.docx"

        fallback_path = Path(os.getcwd()) / fallback_name
        builder.doc.save(str(fallback_path))
        saved_path = fallback_path
        file_name = fallback_path.name
        file_size = saved_path.stat().st_size

    # 5. Build and return Pydantic metadata
    metadata = DocumentMetadata(
        title=doc_title,
        doc_type=doc_type,
        file_name=file_name,
        file_path=str(saved_path.resolve()),
        file_size_bytes=file_size,
        word_count=word_count,
        section_count=max(1, section_count),
        generated_at=datetime.now(UTC),
    )

    # Return serialized model JSON representation
    return metadata.model_dump_json()
